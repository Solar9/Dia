def update_line(words: dict[str, str], outcome: str | None, at: str = "", version: str = "") -> str:
    """The "Check for updates" menu item with the last result: ``None`` before any check."""
    title = words["check_updates"]
    detail = {
        "up_to_date": words["up_to_date"].format(time=at),
        "failed": words["check_failed"].format(time=at),
        "found": words["update_found"].format(version=version),
        "checking": words["checking"],
        "source": words["check_source"],
    }.get(outcome or "")
    return f"{title} — {detail}" if detail and outcome != "checking" else detail or title
